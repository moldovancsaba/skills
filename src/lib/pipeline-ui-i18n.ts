function resolveLanguage<T>(table: Record<UiLanguage, T>, language: UiLanguage): T {
  return table[language] ?? table[FALLBACK_LANGUAGE];
}

export function getPipelineJobLabel(language: UiLanguage, jobType: unknown) {
  const key = typeof jobType === "string" ? jobType : "";
  const labels = resolveLanguage(JOB_LABELS, language);
  return labels[key] || key.replace(/_/g, " ").toLowerCase() || "Queue task";
}

export function getPipelineSourceSignalLabel(language: UiLanguage, sourceSignal: unknown) {
  const key = typeof sourceSignal === "string" ? sourceSignal : "default";
  const labels = resolveLanguage(SOURCE_SIGNAL_LABELS, language);
  return labels[key] || key.replace(/-/g, " ");
}

export function translatePipelineReason(language: UiLanguage, reason: unknown) {
  const value = typeof reason === "string" ? reason : "";
  if (!value) return "";
  const labels = resolveLanguage(STATIC_REASON_LABELS, language);
  return labels[value] || value;
}
